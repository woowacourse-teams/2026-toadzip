package com.toadzip.backend.ingest.mapping.repository;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Connection;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import javax.sql.DataSource;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase;
import org.springframework.boot.jdbc.test.autoconfigure.JdbcTest;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

@JdbcTest
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@Transactional(propagation = Propagation.NOT_SUPPORTED)
@ActiveProfiles("test")
class MyHomeExcludedComplexTrashMigrationTest {

    @Autowired
    private DataSource dataSource;

    @Test
    void 보호_대상이_아닌_제외_원천_단지만_휴지통으로_옮기고_변경_이력을_남긴다() throws Exception {
        try (Connection connection = dataSource.getConnection(); Statement sql = connection.createStatement()) {
            sql.execute("CREATE SCHEMA myhome_excluded_complex_trash_test");
            try {
                connection.setSchema("myhome_excluded_complex_trash_test");
                sql.execute("""
                        CREATE TABLE housing_complexes (
                            id BIGINT PRIMARY KEY, name TEXT, source_complex_identifier TEXT,
                            admin_deleted BOOLEAN NOT NULL DEFAULT FALSE,
                            admin_modified BOOLEAN NOT NULL DEFAULT FALSE,
                            admin_updated_at TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0)
                        """);
                sql.execute("""
                        CREATE TABLE myhome_complex_source_rows (
                            hsmp_sn BIGINT, suply_ty_nm TEXT, style_nm TEXT, house_ty_nm TEXT)
                        """);
                sql.execute("CREATE TABLE myhome_complex_links (housing_complex_id BIGINT, merge_id UUID)");
                sql.execute("CREATE TABLE announcements (id BIGINT PRIMARY KEY, admin_deleted BOOLEAN)");
                sql.execute("CREATE TABLE supply_rows (announcement_id BIGINT, housing_complex_id BIGINT)");
                sql.execute("""
                        CREATE TABLE admin_data_changes (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            resource_type VARCHAR(30) NOT NULL, resource_id BIGINT NOT NULL,
                            action VARCHAR(30) NOT NULL, actor VARCHAR(255) NOT NULL,
                            occurred_at TIMESTAMPTZ NOT NULL, before_value TEXT NOT NULL,
                            after_value TEXT NOT NULL)
                        """);
                sql.execute("""
                        INSERT INTO myhome_complex_source_rows VALUES
                            (1040, '장기전세', '1', '다가구주택'), (1040, '장기전세', NULL, '다가구주택'),
                            (1041, '장기전세', '1', '다가구주택'), (1042, '장기전세', '1', '다가구주택'),
                            (1043, '장기전세', '1', '다가구주택'), (1044, '장기전세', '1', '다가구주택'),
                            (2000, '장기전세', '59A', '아파트'), (1040, '국민임대', '46A', '다가구주택'),
                            (3000, '10년임대', '매입임대', '다세대주택'), (3001, '10년임대', '매입임대', '아파트'),
                            (3001, '10년임대', '59A', '아파트')
                        """);
                sql.execute("""
                        INSERT INTO housing_complexes (id, name, source_complex_identifier, admin_modified) VALUES
                            (1, '아그네스', '1040:LONG_TERM_JEONSE', FALSE),
                            (2, '관리자 수정', '1041:LONG_TERM_JEONSE', TRUE),
                            (3, '승인 연결', '1042:LONG_TERM_JEONSE', FALSE),
                            (4, '공고 연결', '1043:LONG_TERM_JEONSE', FALSE),
                            (5, '삭제 공고 연결', '1044:LONG_TERM_JEONSE', FALSE),
                            (6, '장기전세 아파트', '2000:LONG_TERM_JEONSE', FALSE),
                            (7, '같은 단지 국민임대', '1040:NATIONAL_RENTAL', FALSE),
                            (8, '매입임대주택', '3000:PUBLIC_RENTAL_10Y', FALSE),
                            (9, '일부만 매입임대', '3001:PUBLIC_RENTAL_10Y', FALSE)
                        """);
                sql.execute("""
                        INSERT INTO myhome_complex_links VALUES
                            (1, NULL), (3, '00000000-0000-0000-0000-000000000001')
                        """);
                sql.execute("INSERT INTO announcements VALUES (10, FALSE), (11, TRUE)");
                sql.execute("INSERT INTO supply_rows VALUES (10, 4), (11, 5)");

                ScriptUtils.executeSqlScript(connection, new ClassPathResource(
                        "db/migration/V20261024_01__trash_myhome_excluded_complexes.sql"));

                assertThat(longs(sql, """
                        SELECT id FROM housing_complexes
                        WHERE admin_deleted AND admin_updated_at IS NOT NULL AND version = 1 ORDER BY id
                        """)).containsExactly(1L, 5L, 8L);
                assertThat(longs(sql, "SELECT id FROM housing_complexes WHERE NOT admin_deleted ORDER BY id"))
                        .containsExactly(2L, 3L, 4L, 6L, 7L, 9L);
                assertThat(longs(sql, """
                        SELECT resource_id FROM admin_data_changes
                        WHERE resource_type = 'COMPLEX' AND action = 'DELETE'
                          AND after_value::jsonb ->> 'deleted' = 'true' ORDER BY resource_id
                        """)).containsExactly(1L, 5L, 8L);
            }
            finally {
                connection.setSchema("public");
                sql.execute("DROP SCHEMA myhome_excluded_complex_trash_test CASCADE");
            }
        }
    }

    private List<Long> longs(Statement sql, String query) throws Exception {
        List<Long> values = new ArrayList<>();
        try (var rows = sql.executeQuery(query)) {
            while (rows.next()) {
                values.add(rows.getLong(1));
            }
        }
        return values;
    }
}
