-- GH주택청약센터 공고 원천 수집. 목록·상세 HTML은 저장하지 않고 상세를 지구·주택형·일정·접수처·안내 같은 의미 단위로 둔다.
CREATE TABLE gh_announcement_source (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key varchar(200) NOT NULL UNIQUE,
    pbanc_no varchar(100) NOT NULL,
    board varchar(40) NOT NULL CHECK (board IN ('RENTAL_HOUSE')),
    kind_code varchar(10) NOT NULL,
    title text NOT NULL,
    supply_type text NOT NULL,
    region text NOT NULL,
    posted_date date NOT NULL,
    closing_date date,
    status text,
    original_url text NOT NULL,
    list_url text NOT NULL,
    districts text CHECK (jsonb_typeof(districts::jsonb) = 'array'),
    reception text CHECK (jsonb_typeof(reception::jsonb) = 'object'),
    notice text,
    other_notes text,
    attachments text CHECK (jsonb_typeof(attachments::jsonb) = 'array'),
    collected_at timestamp with time zone NOT NULL
);
CREATE INDEX idx_gh_announcement_collected_at ON gh_announcement_source (collected_at DESC, id DESC);

