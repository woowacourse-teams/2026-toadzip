CREATE TABLE complex_comparison_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    housing_complex_id BIGINT NOT NULL REFERENCES housing_complexes(id) ON DELETE CASCADE,
    category VARCHAR(30) NOT NULL CHECK (category IN ('MYHOME_COMPLEX', 'LH_LEASE_CATALOG')),
    source_key VARCHAR(512) NOT NULL,
    evidence_note VARCHAR(2000) NOT NULL,
    actor VARCHAR(255) NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL,
    UNIQUE (housing_complex_id, category, source_key)
);