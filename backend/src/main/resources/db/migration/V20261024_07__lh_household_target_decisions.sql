CREATE TABLE lh_household_target_decisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    housing_complex_id bigint NOT NULL REFERENCES housing_complexes(id) ON DELETE CASCADE,
    decision varchar(20) NOT NULL,
    chosen_source_key varchar(500),
    sources_fingerprint varchar(64) NOT NULL,
    target_fingerprint varchar(64) NOT NULL,
    reason varchar(2000) NOT NULL,
    actor varchar(255) NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_lh_household_target_decisions_complex UNIQUE (housing_complex_id),
    CONSTRAINT lh_household_target_decisions_decision_check CHECK (decision IN ('USE_SOURCE', 'SKIP')),
    CONSTRAINT lh_household_target_decisions_source_check
        CHECK ((decision = 'USE_SOURCE') = (chosen_source_key IS NOT NULL))
);
