CREATE TABLE supply_row_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    announcement_id bigint NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    source_row_identifier varchar(500) NOT NULL UNIQUE,
    shared_household_count integer CHECK (shared_household_count >= 0),
    source_fingerprint varchar(64) NOT NULL,
    source_url varchar(2048) NOT NULL,
    reason varchar(2000) NOT NULL,
    actor varchar(255) NOT NULL,
    updated_at timestamptz NOT NULL,
    review_required boolean NOT NULL DEFAULT false
);

ALTER TABLE supply_rows ADD COLUMN supply_group_id bigint REFERENCES supply_row_groups(id);
ALTER TABLE supply_rows ADD COLUMN confirmed_target_fingerprint varchar(64);
ALTER TABLE supply_rows ADD CONSTRAINT ck_supply_group_count
    CHECK (supply_group_id IS NULL OR total_supply_household_count IS NULL);
CREATE INDEX idx_supply_rows_group ON supply_rows(supply_group_id);
