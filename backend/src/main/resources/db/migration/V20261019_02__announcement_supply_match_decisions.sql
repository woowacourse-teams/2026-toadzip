CREATE TABLE announcement_supply_match_decisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    row_identifier varchar(500) NOT NULL UNIQUE,
    complex_id bigint REFERENCES housing_complexes(id) ON DELETE SET NULL,
    housing_type_id bigint REFERENCES housing_types(id) ON DELETE SET NULL,
    source_fingerprint varchar(64) NOT NULL,
    target_fingerprint varchar(64) NOT NULL,
    source_url varchar(2048) NOT NULL,
    reason varchar(2000) NOT NULL,
    actor varchar(255) NOT NULL,
    updated_at timestamptz NOT NULL
);
