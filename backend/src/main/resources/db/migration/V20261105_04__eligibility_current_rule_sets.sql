    CHECK (num_nonnulls(fact_code, input_gap_code, referenced_group_id) <= 1),
    CHECK (NOT (interpretation_status = 'INTERPRETED' AND automation_mode = 'AUTOMATIC' AND condition_role IN ('REQUIREMENT','EXCLUSION','OBLIGATION')) OR ((fact_code IS NOT NULL AND operator IS NOT NULL) OR referenced_group_id IS NOT NULL OR input_gap_code IS NOT NULL)),
    CHECK (value_unit IS DISTINCT FROM 'PERCENT_OF_STANDARD' OR (income_standard_table_id IS NOT NULL AND household_size_fact_code IS NOT NULL)),
    CHECK ((reference_date_rule = 'SPECIFIC_DATE') = (reference_date IS NOT NULL)),
    CHECK (COALESCE(operator IN ('IN_REGION_SET','NOT_IN_REGION_SET'), false) = (region_set_id IS NOT NULL)),
    CHECK (input_match = 'EXACT' OR fact_code IS NOT NULL),
    CHECK (id IS DISTINCT FROM replaces_condition_id)
