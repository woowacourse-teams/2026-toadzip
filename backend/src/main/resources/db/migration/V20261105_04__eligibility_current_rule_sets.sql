-- Current structured rule sets only. No evaluation or historical-profile tables.
CREATE TABLE announcement_rule_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    status VARCHAR(10) NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision >= 1),
    recruitment_kind VARCHAR(20) NOT NULL CHECK (recruitment_kind IN
        ('INITIAL', 'ADDITIONAL', 'WAITLIST', 'REGULAR_BATCH', 'CONTINUOUS')),
    applicant_kind VARCHAR(20) NOT NULL CHECK (applicant_kind IN ('INDIVIDUAL', 'ORGANIZATION')),
    has_eligibility_relaxation BOOLEAN NOT NULL,
    source_url VARCHAR(2000),
    source_published_at TIMESTAMPTZ,
    collected_at TIMESTAMPTZ NOT NULL,
    eligibility_reference_date DATE NOT NULL,
    structuring_status VARCHAR(20) NOT NULL CHECK (structuring_status IN ('NOT_STARTED', 'PARTIAL', 'COMPLETE')),
    evaluation_snapshot JSONB,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((status = 'PUBLISHED') = (published_at IS NOT NULL)),
    CHECK ((status = 'PUBLISHED') = (evaluation_snapshot IS NOT NULL)),
    CHECK (status <> 'PUBLISHED' OR (version > 0 AND jsonb_typeof(evaluation_snapshot) = 'object'))
);
CREATE UNIQUE INDEX uk_eligibility_published ON announcement_rule_sets (announcement_id) WHERE status = 'PUBLISHED';
CREATE UNIQUE INDEX uk_eligibility_draft ON announcement_rule_sets (announcement_id) WHERE status = 'DRAFT';

