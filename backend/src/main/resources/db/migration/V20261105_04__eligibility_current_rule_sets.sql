    CHECK (monthly_rent_max_krw IS NULL OR monthly_rent_max_krw >= 0),
    CHECK (conversion_deposit_limit_krw IS NULL OR conversion_deposit_limit_krw >= 0),
    CHECK (deposit_max_krw IS NULL OR (deposit_krw IS NOT NULL AND deposit_max_krw >= deposit_krw)),
    CHECK (amount_precision <> 'RANGE' OR deposit_krw IS NULL OR deposit_max_krw IS NOT NULL),
    CHECK (down_payment_max_krw IS NULL OR (down_payment_krw IS NOT NULL AND down_payment_max_krw >= down_payment_krw)),
    CHECK (amount_precision <> 'RANGE' OR down_payment_krw IS NULL OR down_payment_max_krw IS NOT NULL),
    CHECK (balance_max_krw IS NULL OR (balance_krw IS NOT NULL AND balance_max_krw >= balance_krw)),
    CHECK (amount_precision <> 'RANGE' OR balance_krw IS NULL OR balance_max_krw IS NOT NULL),
