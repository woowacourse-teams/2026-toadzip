CREATE TABLE eligibility_facts (
    code VARCHAR(60) NOT NULL,
    label VARCHAR(100) NOT NULL,
    fact_kind VARCHAR(60) NOT NULL CHECK (fact_kind IN ('INPUT', 'DERIVED')),
