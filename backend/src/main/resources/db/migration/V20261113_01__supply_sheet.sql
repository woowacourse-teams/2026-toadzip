-- 공고 공급표를 병합 칸 그대로 담는다. 공급행(supply_rows)은 공고 주택형(공고 단지 × 신청형) 한 줄이고,
-- 수량과 임대조건은 주택형에서 떼어 칸(주택형 × 공급대상)의 묶음으로 둔다. 공고문에서 한 칸이 여러 주택형·대상에 걸쳐
-- 병합되어 있으면 묶음 하나에 멤버가 여럿이다(예: 55A·55B·55C 당첨 103 / 예비 100).
--
-- 지금은 옛 대상·수 테이블(supply_targets, supply_target_count_groups, supply_row_groups와 supply_rows의 모집수)이 정본이고,
-- 새 표는 V20261113_02의 트리거가 그 테이블에서 다시 만든다. PDF로 보정한 공고는 트리거가 건너뛰고 PDF 보정 적용이 쓴다(_02 머리 주석).
-- 옛 테이블을 그대로 두므로 이전 버전 애플리케이션도 그대로 돈다.

-- 공고 공급대상: 공급표의 대상 칸 하나. 같은 표기라도 신청 조건이 다르면 다른 대상이다. 대상 구분이 없는 표는 '전체' 하나를 둔다.
CREATE TABLE announcement_supply_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements (id) ON DELETE CASCADE,
    label VARCHAR(255) NOT NULL,
    application_condition VARCHAR(255) NOT NULL DEFAULT '',
    display_order INTEGER NOT NULL DEFAULT 0,
    admin_modified BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT uk_announcement_supply_targets UNIQUE (announcement_id, label, application_condition),
    CONSTRAINT ck_announcement_supply_targets_label CHECK (btrim(label) <> '')
);

-- 공급표 칸: 이 주택형에 이 대상이 있다. 수량·임대조건 묶음의 멤버이고, 수나 금액이 없는 칸도 남는다.
-- 옛 대상에서 온 칸은 옛 대상 ID를 그대로 쓴다(공개 응답의 supplyTargetId가 이어진다). 그 밖의 칸('전체')은 옛 대상 시퀀스에서
-- ID를 받아 옛 대상 ID와 겹치지 않는다. ID는 다시 만들기 함수가 정한다.
CREATE TABLE supply_row_targets (
    id BIGINT PRIMARY KEY,
    supply_row_id BIGINT NOT NULL REFERENCES supply_rows (id) ON DELETE CASCADE,
    supply_target_id BIGINT NOT NULL REFERENCES announcement_supply_targets (id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_supply_row_targets UNIQUE (supply_row_id, supply_target_id)
);

CREATE INDEX idx_supply_row_targets_target ON supply_row_targets (supply_target_id);

-- 수량 묶음: 공급표의 수량 칸 하나. WINNER는 모집(당첨) 세대수, RESERVE는 예비자 수다.
CREATE TABLE supply_quotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements (id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL,
    household_count INTEGER NOT NULL,
    admin_modified BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT ck_supply_quotas_kind CHECK (kind IN ('WINNER', 'RESERVE')),
    CONSTRAINT ck_supply_quotas_household_count CHECK (household_count >= 0)
);

CREATE INDEX idx_supply_quotas_announcement ON supply_quotas (announcement_id);

CREATE TABLE supply_quota_members (
    supply_quota_id BIGINT NOT NULL REFERENCES supply_quotas (id) ON DELETE CASCADE,
    supply_row_target_id BIGINT NOT NULL REFERENCES supply_row_targets (id) ON DELETE CASCADE,
    PRIMARY KEY (supply_quota_id, supply_row_target_id)
);

CREATE INDEX idx_supply_quota_members_cell ON supply_quota_members (supply_row_target_id);

-- 임대조건: 금액 칸 한 세트. 병합된 금액 칸은 멤버가 여럿이고, 칸 하나는 임대조건 하나만 가진다.
CREATE TABLE lease_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements (id) ON DELETE CASCADE,
    rental_deposit NUMERIC(38, 2),
    monthly_rent NUMERIC(38, 2),
    converted_deposit NUMERIC(38, 2),
    admin_modified BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT ck_lease_terms_amounts CHECK (
        (rental_deposit IS NULL OR rental_deposit >= 0)
        AND (monthly_rent IS NULL OR monthly_rent >= 0)
        AND (converted_deposit IS NULL OR converted_deposit >= 0)
    )
);

CREATE INDEX idx_lease_terms_announcement ON lease_terms (announcement_id);

CREATE TABLE lease_term_members (
    lease_terms_id BIGINT NOT NULL REFERENCES lease_terms (id) ON DELETE CASCADE,
    supply_row_target_id BIGINT NOT NULL REFERENCES supply_row_targets (id) ON DELETE CASCADE,
    PRIMARY KEY (lease_terms_id, supply_row_target_id),
    CONSTRAINT uk_lease_term_members_cell UNIQUE (supply_row_target_id)
);

-- 공급행을 지울 때 남은 옛 대상이 막지 않게 한다(공급행의 칸은 위에서 CASCADE로 지운다).
DO $$
DECLARE
    fk_name TEXT;
BEGIN
    SELECT conname INTO fk_name
    FROM pg_constraint
    WHERE conrelid = 'supply_targets'::regclass
      AND confrelid = 'supply_rows'::regclass
      AND contype = 'f';
    IF fk_name IS NOT NULL THEN
        EXECUTE format('ALTER TABLE supply_targets DROP CONSTRAINT %I', fk_name);
    END IF;
END $$;

ALTER TABLE supply_targets
    ADD CONSTRAINT fk_supply_targets_supply_row FOREIGN KEY (supply_row_id) REFERENCES supply_rows (id) ON DELETE CASCADE;

CREATE INDEX idx_supply_target_count_groups_row_kind ON supply_target_count_groups (supply_row_id, kind);
