-- 칸 ID는 지금까지 옛 대상 시퀀스에서 받았다(옛 대상에서 온 칸은 옛 대상 ID). 그 표를 지우므로 칸 표가 자기 ID를 만든다.
-- 공개 응답에 나간 칸·옛 대상 ID와 겹치지 않게 둘 중 큰 값 다음부터 준다.
ALTER TABLE supply_row_targets ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('supply_row_targets', 'id'), GREATEST(
        (SELECT COALESCE(MAX(id), 0) FROM supply_row_targets),
        COALESCE(pg_sequence_last_value(pg_get_serial_sequence('supply_targets', 'id')::regclass), 0),
        1));

-- 2. 접힌 행 나누기. 옛 공급행 하나가 대표 주택형 밖의 주택형도 함께 가리키면(supply_row_housing_types) 그 주택형마다 공급행을
--    하나씩 더 만든다. 새 행은 원래 행의 단지·공고 단지·입주 예정월·공급구분·PNU·제외·관리자 수정 표시를 그대로 갖고, 이름은 그
--    주택형 이름이다. 원래 행도 대표 주택형 이름으로 바꿔 행마다 자기 주택형 이름을 갖는다(공고문 이름 '26A/B/C' → 26A·26B·26C).
--    면적 보정은 원래 행에만 남긴다(대표 주택형의 면적이다).
--    원래 행의 칸(공급대상)을 새 행에도 같은 공급대상으로 두고, 원래 칸이 든 수량 묶음과 임대조건에 새 칸도 멤버로 넣는다.
--    그래서 원래 행의 수는 나눈 행들이 함께 쓰는 수가 된다(PDF 추출의 "49A·49B·49C 함께 모집 70"과 같은 모양). 묶음과 임대조건은
--    새로 만들지 않으므로 공고 모집수 합계는 그대로다.
CREATE TEMPORARY TABLE split_supply_rows ON COMMIT DROP AS
SELECT r.id AS origin_id,
       h.housing_type_id,
       t.name AS type_name,
       'SHEET:split:' || r.id || ':' || h.housing_type_id AS source_identifier,
       ROW_NUMBER() OVER (PARTITION BY r.id ORDER BY t.name, t.id) AS position
FROM supply_row_housing_types h
JOIN supply_rows r ON r.id = h.supply_row_id
JOIN housing_types t ON t.id = h.housing_type_id
WHERE h.housing_type_id IS DISTINCT FROM r.housing_type_id;

INSERT INTO supply_rows (announcement_id, housing_complex_id, housing_type_id, announcement_complex_id,
                         source_supply_row_identifier, display_order, source_complex_name, source_housing_type_name,
                         announcement_housing_type_name, supply_pnu, expected_move_in_month, supply_category,
                         admin_modified, admin_excluded)
SELECT r.announcement_id, r.housing_complex_id, s.housing_type_id, r.announcement_complex_id,
       s.source_identifier, r.display_order, r.source_complex_name, s.type_name,
       s.type_name, r.supply_pnu, r.expected_move_in_month, r.supply_category,
       r.admin_modified, r.admin_excluded
FROM split_supply_rows s
JOIN supply_rows r ON r.id = s.origin_id;

UPDATE supply_rows r SET announcement_housing_type_name = t.name
FROM housing_types t
WHERE t.id = r.housing_type_id
  AND r.id IN (SELECT origin_id FROM split_supply_rows);

-- 나눈 행은 원래 행 바로 뒤에 오게 그 공고의 표시 순서를 다시 매긴다.
UPDATE supply_rows r SET display_order = ordered.display_order
FROM (
    SELECT row_value.id,
           (ROW_NUMBER() OVER (PARTITION BY row_value.announcement_id
               ORDER BY COALESCE(origin.display_order, row_value.display_order), COALESCE(split.origin_id, row_value.id),
                        COALESCE(split.position, 0)) - 1)::INTEGER AS display_order
    FROM supply_rows row_value
    LEFT JOIN split_supply_rows split ON split.source_identifier = row_value.source_supply_row_identifier
    LEFT JOIN supply_rows origin ON origin.id = split.origin_id
    WHERE row_value.announcement_id IN (
        SELECT origin_row.announcement_id FROM supply_rows origin_row
        WHERE origin_row.id IN (SELECT origin_id FROM split_supply_rows))
) ordered
WHERE r.id = ordered.id;

CREATE TEMPORARY TABLE split_supply_cells ON COMMIT DROP AS
SELECT c.id AS origin_cell_id, created.id AS split_row_id, c.supply_target_id, c.display_order
FROM split_supply_rows s
JOIN supply_rows created ON created.source_supply_row_identifier = s.source_identifier
JOIN supply_row_targets c ON c.supply_row_id = s.origin_id;

INSERT INTO supply_row_targets (supply_row_id, supply_target_id, display_order)
SELECT split_row_id, supply_target_id, display_order FROM split_supply_cells;

INSERT INTO supply_quota_members (supply_quota_id, supply_row_target_id)
SELECT m.supply_quota_id, created.id
FROM supply_quota_members m
JOIN split_supply_cells s ON s.origin_cell_id = m.supply_row_target_id
JOIN supply_row_targets created ON created.supply_row_id = s.split_row_id AND created.supply_target_id = s.supply_target_id;

INSERT INTO lease_term_members (lease_terms_id, supply_row_target_id)
SELECT m.lease_terms_id, created.id
FROM lease_term_members m
JOIN split_supply_cells s ON s.origin_cell_id = m.supply_row_target_id
JOIN supply_row_targets created ON created.supply_row_id = s.split_row_id AND created.supply_target_id = s.supply_target_id;

