CREATE TABLE admin_supply_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements(id),
    target VARCHAR(64) NOT NULL,
    outcome VARCHAR(20) NOT NULL CHECK (outcome IN ('VERIFIED', 'ON_HOLD')),
    checked_values TEXT NOT NULL,
    evidence TEXT NOT NULL,
    note VARCHAR(2000) NOT NULL,
    source_url VARCHAR(2048) NOT NULL,
    source_page VARCHAR(100),
    actor VARCHAR(255) NOT NULL,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_admin_supply_reviews_latest ON admin_supply_reviews(announcement_id, target, id DESC);
