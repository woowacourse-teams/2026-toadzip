-- PDF 보정 화면이 같은 PDF를 다시 추출하지 않도록 AI 추출 결과를 남긴다. 공고를 지우면 함께 지운다.
CREATE TABLE announcement_pdf_extractions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    pdf_sha256 VARCHAR(64) NOT NULL,
    file_name VARCHAR(500) NOT NULL,
    result TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_announcement_pdf_extractions_latest
    ON announcement_pdf_extractions (announcement_id, created_at DESC, id DESC);
