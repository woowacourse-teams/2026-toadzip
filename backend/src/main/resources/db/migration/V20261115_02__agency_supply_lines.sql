-- 기관(LH·GH) 원천 공급은 준비 데이터(agency_supply_lines)로 두고, 공고 공급표(정본)는 공고문으로 확정한 공고만 갖는다.
-- 공고의 supply_confirmed_at이 정본 확정이다(supply_owner 대신). 조회는 확정한 공고는 정본, 확정 전 공고는 준비 줄을 공급표로 바꿔 보인다.
--   1. 준비 테이블과 확정 열을 만든다. 관리자가 공고 단지의 단지 연결을 풀 수 있게(단지 없음 + ADMIN) 연결 검사를 넓힌다.
--   2. LH 원천 소유 정본(관리자 흔적 없음)을 칸마다 LH 준비 줄로 옮긴다. 다음 LH 정제가 원천 줄 키로 다시 쓴다.
--   3. GH 공고는 수집한 지구 원천에서 준비 줄을 만든다(GH 정제 규칙과 같다).
--   4. 정본이 남는 공고를 확정한다: 공고문 소유 정본, 관리자 흔적이 있는 LH 원천 소유 정본, LH 공고 ID 없는 등록 공고.
--      관리자가 손대지 않은 GH 정제 틀(원천이 있는 것만)은 준비 줄로 대신하고 정본에서 지운다. 옛 GH 정제가 관리자가 맡은
--      공고로 본 것(관리자 수정 시각, 공개, 관리자 단지 연결)은 정본으로 남긴다.
--   5. 옮긴 정본을 지우고 supply_owner를 지운다.

CREATE TABLE agency_supply_lines (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id          BIGINT         NOT NULL REFERENCES announcements (id) ON DELETE CASCADE,
    announcement_complex_id  BIGINT REFERENCES announcement_complexes (id) ON DELETE SET NULL,
    agency                   VARCHAR(10)    NOT NULL,
    source_line_key          VARCHAR(255)   NOT NULL,
    display_order            INTEGER        NOT NULL,
    complex_name             VARCHAR(255)   NOT NULL,
    housing_type_name        VARCHAR(255)   NOT NULL,
    exclusive_area           NUMERIC(10, 4),
    supply_area              NUMERIC(10, 4),
    target_label             VARCHAR(255),
    household_count          INTEGER,
    rental_deposit           NUMERIC(38, 2),
    monthly_rent             NUMERIC(38, 2),
    expected_move_in_month   VARCHAR(255),
    supply_category          VARCHAR(255)   NOT NULL,
    CONSTRAINT uk_agency_supply_lines_source_line UNIQUE (announcement_id, source_line_key),
    CONSTRAINT ck_agency_supply_lines_agency CHECK (agency IN ('LH', 'GH')),
    CONSTRAINT ck_agency_supply_lines_counts CHECK (display_order >= 0
        AND (household_count IS NULL OR household_count >= 0)),
    CONSTRAINT ck_agency_supply_lines_supply_category CHECK (supply_category IN ('NEW_SUPPLY', 'RESUPPLY'))
);

CREATE INDEX idx_agency_supply_lines_announcement_complex ON agency_supply_lines (announcement_complex_id);

ALTER TABLE announcements ADD COLUMN supply_confirmed_at TIMESTAMP WITH TIME ZONE;

ALTER TABLE announcement_complexes DROP CONSTRAINT ck_announcement_complexes_link;
ALTER TABLE announcement_complexes ADD CONSTRAINT ck_announcement_complexes_link CHECK (
    (housing_complex_id IS NULL AND (link_method IS NULL OR link_method = 'ADMIN'))
    OR (housing_complex_id IS NOT NULL AND link_method IN ('AUTO', 'ADMIN', 'MIGRATED')));

-- 관리자 흔적: 관리자가 고치거나 제외한 공급행, 고친 공급대상·모집수·임대조건.
CREATE TEMPORARY TABLE admin_touched_supply ON COMMIT DROP AS
SELECT a.id AS announcement_id
FROM announcements a
WHERE EXISTS (SELECT 1 FROM supply_rows r WHERE r.announcement_id = a.id AND (r.admin_modified OR r.admin_excluded))
   OR EXISTS (SELECT 1 FROM announcement_supply_targets t WHERE t.announcement_id = a.id AND t.admin_modified)
   OR EXISTS (SELECT 1 FROM supply_quotas q WHERE q.announcement_id = a.id AND q.admin_modified)
   OR EXISTS (SELECT 1 FROM lease_terms l WHERE l.announcement_id = a.id AND l.admin_modified);

-- 준비 데이터로 옮길 정본: 관리자 흔적 없는 LH 원천 소유 LH 공고, 관리자가 손대지 않은 GH 정제 틀(GH 원천이 있는 공고).
CREATE TEMPORARY TABLE staged_announcements ON COMMIT DROP AS
SELECT a.id AS announcement_id, 'LH' AS agency
FROM announcements a
WHERE a.supply_owner = 'LH_SOURCE' AND a.lh_pan_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM admin_touched_supply t WHERE t.announcement_id = a.id)
UNION ALL
SELECT a.id, 'GH'
FROM announcements a
WHERE a.provider = 'GH' AND a.supply_owner = 'ANNOUNCEMENT_DOCUMENT' AND a.admin_updated_at IS NULL
  AND a.release_status <> 'PUBLISHED'
  AND NOT EXISTS (SELECT 1 FROM announcement_complexes c WHERE c.announcement_id = a.id AND c.link_method = 'ADMIN')
  AND NOT EXISTS (SELECT 1 FROM admin_touched_supply t WHERE t.announcement_id = a.id)
  AND EXISTS (SELECT 1 FROM gh_announcement_source s
              WHERE s.source_key = a.source_announcement_identifier AND s.districts IS NOT NULL);

-- 2. LH 준비 줄: 정본 칸 하나가 원천 줄 하나다. '전체' 칸은 대상 표기 없이(형명 규칙으로 정함), 다른 칸은 그 표기로 둔다.
--    형명은 공급행의 이은 형명(" · ") 중 그 표기의 형명이다: 표기와 같은 형명, 끝이 (표기)·[표기]인 형명, 없으면 첫 형명.
--    세대수는 그 칸만 멤버인 모집수의 합, 금액은 그 칸의 임대조건이다.
WITH cells AS (
    SELECT r.announcement_id, r.announcement_complex_id, r.source_complex_name, r.source_housing_type_name,
           -- 원천 면적이 없던 행은 옛 정제·연결이 이어 둔 주택타입의 면적을 옮긴다. 준비 줄은 주택타입 열이 없어 읽을 때 같은
           -- 면적으로 그 주택타입을 다시 고른다(같은 면적이 하나뿐일 때).
           COALESCE(r.lh_exclusive_area, r.announcement_exclusive_area, linked.exclusive_area) AS exclusive_area,
           COALESCE(r.announcement_supply_area, linked.supply_area) AS announcement_supply_area,
           r.expected_move_in_month, r.supply_category, c.id AS cell_id, t.label,
           string_to_array(r.source_housing_type_name, ' · ') AS names,
           ROW_NUMBER() OVER (PARTITION BY r.announcement_id
                              ORDER BY r.display_order, r.id, c.display_order, c.id) - 1 AS line_order
    FROM supply_rows r
    JOIN staged_announcements s ON s.announcement_id = r.announcement_id AND s.agency = 'LH'
    LEFT JOIN housing_types linked ON linked.id = r.housing_type_id AND NOT linked.admin_deleted
    JOIN supply_row_targets c ON c.supply_row_id = r.id
    JOIN announcement_supply_targets t ON t.id = c.supply_target_id
    WHERE NOT (t.label = '전체' AND EXISTS (
        SELECT 1 FROM supply_row_targets other JOIN announcement_supply_targets other_target
          ON other_target.id = other.supply_target_id
        WHERE other.supply_row_id = r.id AND other_target.label <> '전체'))
)
INSERT INTO agency_supply_lines (announcement_id, announcement_complex_id, agency, source_line_key, display_order,
                                 complex_name, housing_type_name, exclusive_area, supply_area, target_label,
                                 household_count, rental_deposit, monthly_rent, expected_move_in_month, supply_category)
SELECT cells.announcement_id, cells.announcement_complex_id, 'LH', 'MIGRATED:' || cells.cell_id, cells.line_order,
       cells.source_complex_name,
       CASE WHEN cells.label = '전체' THEN cells.source_housing_type_name
            ELSE COALESCE(
                (SELECT name FROM unnest(cells.names) name WHERE name = cells.label LIMIT 1),
                (SELECT name FROM unnest(cells.names) name
                 WHERE right(name, length(cells.label) + 2) IN ('(' || cells.label || ')', '[' || cells.label || ']')
                 LIMIT 1),
                cells.names[1]) END,
       cells.exclusive_area, cells.announcement_supply_area,
       CASE WHEN cells.label = '전체' THEN NULL ELSE cells.label END,
       (SELECT SUM(q.household_count) FROM supply_quotas q JOIN supply_quota_members m ON m.supply_quota_id = q.id
        WHERE m.supply_row_target_id = cells.cell_id AND q.kind = 'WINNER'
          AND (SELECT COUNT(*) FROM supply_quota_members all_members WHERE all_members.supply_quota_id = q.id) = 1),
       lease.rental_deposit, lease.monthly_rent, cells.expected_move_in_month, cells.supply_category
FROM cells
LEFT JOIN LATERAL (
    SELECT l.rental_deposit, l.monthly_rent
    FROM lease_terms l JOIN lease_term_members lm ON lm.lease_terms_id = l.id
    WHERE lm.supply_row_target_id = cells.cell_id
    ORDER BY l.id LIMIT 1
) lease ON true;

-- 3. GH 준비 줄: 지구의 공고 단지가 있는 지구의 주택형마다 한 줄. 키는 {공고 식별자}:{지구명}:{주택형 코드, 없으면 형명},
--    같은 키는 #2부터 붙인다. 세대수·전용면적은 숫자일 때만, 공급구분은 제목에 '예비입주자'가 있으면 재공급이다.
WITH districts AS (
    SELECT a.id AS announcement_id, a.source_announcement_identifier AS identifier, s.title,
           district.value AS district, district.ordinality AS district_order
    FROM announcements a
    JOIN gh_announcement_source s ON s.source_key = a.source_announcement_identifier AND s.districts IS NOT NULL
    CROSS JOIN LATERAL jsonb_array_elements(s.districts::jsonb) WITH ORDINALITY district(value, ordinality)
    WHERE a.provider = 'GH'
), types AS (
    SELECT d.announcement_id, d.identifier, d.title, ac.id AS announcement_complex_id,
           BTRIM(d.district ->> 'name') AS complex_name, housing_type.value AS housing_type,
           d.district_order, housing_type.ordinality AS type_order
    FROM districts d
    JOIN announcement_complexes ac
      ON ac.announcement_id = d.announcement_id AND ac.source_complex_name = BTRIM(d.district ->> 'name')
    CROSS JOIN LATERAL jsonb_array_elements(COALESCE(d.district -> 'housingTypes', '[]'::jsonb))
        WITH ORDINALITY housing_type(value, ordinality)
    WHERE BTRIM(COALESCE(d.district ->> 'name', '')) <> ''
      AND BTRIM(COALESCE(housing_type.value ->> 'name', '')) <> ''
), keyed AS (
    SELECT types.*,
           types.identifier || ':' || types.complex_name || ':'
               || COALESCE(NULLIF(BTRIM(types.housing_type ->> 'houseTypeCode'), ''), types.housing_type ->> 'name')
               AS base_key,
           REPLACE(BTRIM(COALESCE(types.housing_type ->> 'supplyCount', '')), ',', '') AS supply_count,
           REPLACE(BTRIM(COALESCE(types.housing_type ->> 'exclusiveArea', '')), ',', '') AS exclusive_area,
           ROW_NUMBER() OVER (PARTITION BY types.announcement_id ORDER BY types.district_order, types.type_order) - 1
               AS line_order
    FROM types
), numbered AS (
    SELECT keyed.*, ROW_NUMBER() OVER (PARTITION BY keyed.announcement_id, keyed.base_key
                                       ORDER BY keyed.line_order) AS key_rank
    FROM keyed
)
INSERT INTO agency_supply_lines (announcement_id, announcement_complex_id, agency, source_line_key, display_order,
                                 complex_name, housing_type_name, exclusive_area, household_count, supply_category)
SELECT n.announcement_id, n.announcement_complex_id, 'GH',
       LEFT(CASE WHEN n.key_rank = 1 THEN n.base_key ELSE n.base_key || '#' || n.key_rank END, 255),
       n.line_order, n.complex_name,
       CASE WHEN length(BTRIM(n.housing_type ->> 'name')) <= 255 THEN BTRIM(n.housing_type ->> 'name')
            ELSE LEFT(BTRIM(n.housing_type ->> 'name'), 254) || '…' END,
       CASE WHEN n.exclusive_area ~ '^[0-9]{1,6}(\.[0-9]{1,4})?$' THEN n.exclusive_area::numeric END,
       CASE WHEN n.supply_count ~ '^[0-9]{1,7}$' THEN n.supply_count::integer END,
       CASE WHEN n.title LIKE '%예비입주자%' THEN 'RESUPPLY' ELSE 'NEW_SUPPLY' END
FROM numbered n;

-- 4. 정본이 남는 공고를 확정한다. 확정 시각은 관리자 수정 시각, 없으면 이행 시각이다.
UPDATE announcements a
SET supply_confirmed_at = COALESCE(a.admin_updated_at, CURRENT_TIMESTAMP)
WHERE EXISTS (SELECT 1 FROM supply_rows r WHERE r.announcement_id = a.id)
  AND NOT EXISTS (SELECT 1 FROM staged_announcements s WHERE s.announcement_id = a.id);

-- 5. 준비 데이터로 옮긴 공고의 정본을 지운다(칸·묶음 멤버는 FK로 함께 지워진다).
DELETE FROM lease_terms l USING staged_announcements s WHERE l.announcement_id = s.announcement_id;
DELETE FROM supply_quotas q USING staged_announcements s WHERE q.announcement_id = s.announcement_id;
DELETE FROM supply_rows r USING staged_announcements s WHERE r.announcement_id = s.announcement_id;
DELETE FROM announcement_supply_targets t USING staged_announcements s WHERE t.announcement_id = s.announcement_id;

ALTER TABLE announcements DROP COLUMN supply_owner;
