-- 한 공급행 안에서 대상 여럿이 함께 쓰는 모집수(공통 모집수). 공고문이 '청년(소득 없음)·청년(소득 있음) 예비 20명'처럼
-- 대상끼리 한 번만 적은 수를 대상마다 나누거나 같은 수를 중복 저장하지 않고 묶음 하나에 한 번만 둔다.
-- 묶음은 종류(SUPPLY 공급세대수, RESERVE 예비자수)마다 따로라, 모집수는 A·B가, 예비자 수는 A·B·C가 함께 써도 담을 수 있다.
-- 묶인 대상의 같은 칸은 비워 둔다. 새 표와 비어도 되는 칸만 더하므로 이전 버전 애플리케이션도 그대로 돈다.
CREATE TABLE supply_target_count_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supply_row_id BIGINT NOT NULL REFERENCES supply_rows (id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL,
    household_count INTEGER NOT NULL,
    CONSTRAINT supply_target_count_groups_kind_check CHECK (kind IN ('SUPPLY', 'RESERVE')),
    CONSTRAINT supply_target_count_groups_household_count_check CHECK (household_count >= 0)
);

CREATE INDEX idx_supply_target_count_groups_row ON supply_target_count_groups (supply_row_id);

ALTER TABLE supply_targets
    ADD COLUMN supply_count_group_id BIGINT REFERENCES supply_target_count_groups (id) ON DELETE SET NULL,
    ADD COLUMN reserve_count_group_id BIGINT REFERENCES supply_target_count_groups (id) ON DELETE SET NULL;

CREATE INDEX idx_supply_targets_supply_count_group ON supply_targets (supply_count_group_id);
CREATE INDEX idx_supply_targets_reserve_count_group ON supply_targets (reserve_count_group_id);
