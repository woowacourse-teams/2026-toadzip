CREATE TABLE lh_household_complex_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    source_key varchar(500) NOT NULL,
    housing_complex_id bigint REFERENCES housing_complexes(id) ON DELETE SET NULL,
    source_fingerprint varchar(64) NOT NULL,
    target_fingerprint varchar(64) NOT NULL,
    source_url varchar(2048),
    reason varchar(2000) NOT NULL,
    actor varchar(255) NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_lh_household_complex_links_source UNIQUE (source_key)
);
