-- Additive transition: previously deployed eligibility migrations and stored data remain untouched.
-- Internal content references are validated as a typed aggregate before atomic save/publication.
CREATE TABLE basic_comparison_rule_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED')),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    schema_version INTEGER NOT NULL DEFAULT 2 CHECK (schema_version = 2),
    content JSONB NOT NULL CHECK (jsonb_typeof(content) = 'object'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ,
    CONSTRAINT basic_comparison_publication_state CHECK (
        (status = 'DRAFT' AND version = 0 AND published_at IS NULL)
        OR (status = 'PUBLISHED' AND version > 0 AND published_at IS NOT NULL)
    ),
    CONSTRAINT basic_comparison_current_status UNIQUE (announcement_id, status)
);

CREATE TABLE basic_comparison_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    version BIGINT NOT NULL CHECK (version > 0),
    input_contract_version INTEGER NOT NULL DEFAULT 2 CHECK (input_contract_version = 2),
    profile JSONB NOT NULL CHECK (jsonb_typeof(profile) = 'object'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
