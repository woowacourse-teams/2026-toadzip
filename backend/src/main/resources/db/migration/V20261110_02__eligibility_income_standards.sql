-- 신청자격 소득 조건이 참조하는 소득 기준표. 같은 ID의 표는 공개 내용이 참조하는 동안 바꾸지 않는다.
CREATE TABLE income_standard_tables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    standard_kind VARCHAR(60) NOT NULL CHECK (standard_kind IN ('URBAN_WORKER_MONTHLY_INCOME', 'STANDARD_MEDIAN_INCOME')),
    base_year BIGINT NOT NULL,
    source_note VARCHAR(500) NOT NULL,
    extra_per_person_krw BIGINT,
    max_listed_household_size BIGINT NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (standard_kind, base_year),
    CHECK (max_listed_household_size >= 1),
    CHECK (base_year BETWEEN 1900 AND 9999),
    CHECK (extra_per_person_krw IS NULL OR extra_per_person_krw >= 0)
);

CREATE TABLE income_standard_values (
    table_id BIGINT NOT NULL,
    household_size BIGINT NOT NULL,
    amount_100_krw BIGINT NOT NULL,
    PRIMARY KEY (table_id, household_size),
    CHECK (household_size >= 1),
    CHECK (amount_100_krw > 0)
);

ALTER TABLE income_standard_values ADD FOREIGN KEY (table_id) REFERENCES income_standard_tables (id);
