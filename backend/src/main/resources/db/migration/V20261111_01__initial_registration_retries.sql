ALTER TABLE initial_registration_targets
    ADD COLUMN information_fingerprint varchar(64),
    ADD COLUMN information_complex_name text,
    ADD COLUMN information_evidence text,
    ADD COLUMN information_checked_by varchar(255),
    ADD COLUMN information_checked_at timestamptz;

CREATE TABLE initial_registration_type_names (
    source_complex_identifier varchar(255) NOT NULL REFERENCES initial_registration_targets,
    source_key text NOT NULL,
    housing_type_name text NOT NULL,
    PRIMARY KEY (source_complex_identifier, source_key)
);

CREATE TABLE initial_registration_failures (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_complex_identifier varchar(255) NOT NULL,
    detail text NOT NULL,
    failed_at timestamptz NOT NULL,
    actor varchar(255),
    execution_id uuid
);

CREATE INDEX idx_initial_registration_failures_target
    ON initial_registration_failures (source_complex_identifier, failed_at DESC, id DESC);

-- 이전 버전에서 보존하던 현재 실패도 재처리 전에 이력으로 남긴다.
INSERT INTO initial_registration_failures (source_complex_identifier, detail, failed_at)
SELECT source_complex_identifier, detail, checked_at
FROM initial_registration_targets WHERE status = 'FAILED';
