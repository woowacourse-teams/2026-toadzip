CREATE TABLE admin_comparison_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource VARCHAR(20) NOT NULL CHECK (resource IN ('COMPLEX', 'ANNOUNCEMENT')),
    resource_id BIGINT NOT NULL,
    target VARCHAR(80) NOT NULL,
    category VARCHAR(40) NOT NULL,
    source_key VARCHAR(512) NOT NULL,
    evidence_note VARCHAR(2000) NOT NULL,
    actor VARCHAR(255) NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(resource, resource_id, target, category, source_key)
);
CREATE TABLE admin_comparison_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource VARCHAR(20) NOT NULL CHECK (resource IN ('COMPLEX', 'ANNOUNCEMENT')),
    resource_id BIGINT NOT NULL,
    target VARCHAR(80) NOT NULL,
    evidence JSONB NOT NULL,
    checked_values JSONB NOT NULL,
    evidence_note VARCHAR(2000) NOT NULL,
    actor VARCHAR(255) NOT NULL,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_admin_comparison_checks_latest
    ON admin_comparison_checks(resource, resource_id, target, id DESC);
