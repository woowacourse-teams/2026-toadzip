CREATE TABLE lh_supply_row_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    source_announcement_identifier varchar(100) NOT NULL,
    lh_supply_row_identifier varchar(200) NOT NULL,
    myhome_source_row_identifier varchar(500) NOT NULL,
    lh_source_fingerprint varchar(64) NOT NULL,
    myhome_source_fingerprint varchar(64) NOT NULL,
    source_url varchar(2048) NOT NULL,
    reason varchar(2000) NOT NULL,
    actor varchar(255) NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_lh_supply_row_links_row UNIQUE (source_announcement_identifier, lh_supply_row_identifier)
);
