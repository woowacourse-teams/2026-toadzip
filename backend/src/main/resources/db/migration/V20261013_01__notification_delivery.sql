CREATE INDEX idx_notification_subscriptions_audience
    ON notification_subscriptions (target_type, target_id, user_id) WHERE active;

CREATE TABLE notification_outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key VARCHAR(512) NOT NULL UNIQUE,
    announcement_id BIGINT NOT NULL,
    source_identifier VARCHAR(255) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','COMPLETED','SKIPPED','FAILED')),
    target_snapshot TEXT,
    snapshot_at TIMESTAMPTZ,
    recipient_cursor BIGINT NOT NULL DEFAULT 0,
    recipient_upper_bound BIGINT,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error_code VARCHAR(100)
);
-- Immutable announcement IDs intentionally survive physical source deletion and preserve event-key tombstones.
CREATE INDEX idx_notification_outbox_due ON notification_outbox_events(next_attempt_at,id) WHERE status='PENDING';

CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES notification_outbox_events(id),
    announcement_id BIGINT NOT NULL,
    title VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    read_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_user_notification_event UNIQUE (user_id,event_id)
);
CREATE INDEX idx_user_notifications_page ON user_notifications(user_id,created_at DESC,id DESC);
CREATE INDEX idx_user_notifications_unread ON user_notifications(user_id,expires_at) WHERE read_at IS NULL;
CREATE INDEX idx_user_notifications_expiry ON user_notifications(expires_at,id);

CREATE TABLE notification_push_devices (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    fid VARCHAR(512) NOT NULL UNIQUE,
    binding_version BIGINT NOT NULL CHECK (binding_version > 0),
    enabled BOOLEAN NOT NULL,
    consented_at TIMESTAMPTZ NOT NULL,
    registered_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_notification_push_devices_user ON notification_push_devices(user_id) WHERE enabled;

CREATE TABLE notification_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES user_notifications(id) ON DELETE CASCADE,
    device_id UUID NOT NULL REFERENCES notification_push_devices(id) ON DELETE CASCADE,
    device_binding_version BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','SENDING','RETRY','SENT','SKIPPED','FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at TIMESTAMPTZ NOT NULL,
    lease_token UUID,
    lease_until TIMESTAMPTZ,
    provider_message_id VARCHAR(512),
    last_error_code VARCHAR(100),
    finished_at TIMESTAMPTZ,
    CONSTRAINT uk_notification_delivery_device UNIQUE(notification_id,device_id,device_binding_version),
    CONSTRAINT ck_notification_delivery_lease CHECK (
        (status='SENDING' AND lease_token IS NOT NULL AND lease_until IS NOT NULL)
        OR (status<>'SENDING' AND lease_token IS NULL AND lease_until IS NULL))
);
CREATE INDEX idx_notification_deliveries_due ON notification_deliveries(next_attempt_at,id)
    WHERE status IN ('PENDING','RETRY');
CREATE INDEX idx_notification_deliveries_lease ON notification_deliveries(lease_until,id) WHERE status='SENDING';
CREATE INDEX idx_notification_deliveries_finished ON notification_deliveries(finished_at,id)
    WHERE status IN ('SENT','SKIPPED','FAILED');
