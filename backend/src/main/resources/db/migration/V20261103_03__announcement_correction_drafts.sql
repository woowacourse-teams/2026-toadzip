-- 관리자가 PDF 보정 화면에서 진행 중인 작업을 관리자별·공고별로 하나씩 임시저장한다.
-- payload는 화면이 만든 작업 상태 그대로이며 서버는 해석하지 않는다. 공개 데이터에는 반영하지 않는다.
-- revision은 저장할 때마다 1씩 늘고, 화면은 본 revision을 함께 보내 다른 탭의 저장을 덮어쓰지 않는다.
CREATE TABLE announcement_correction_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    admin_login_identifier VARCHAR(255) NOT NULL,
    payload JSONB NOT NULL,
    base_snapshot_token VARCHAR(64) NOT NULL,
    pdf_sha256 VARCHAR(64),
    extraction_id BIGINT,
    revision BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ux_announcement_correction_drafts_owner UNIQUE (announcement_id, admin_login_identifier),
    CONSTRAINT ck_announcement_correction_drafts_payload CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT ck_announcement_correction_drafts_revision CHECK (revision >= 1)
);
