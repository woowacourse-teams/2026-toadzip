-- Python AI 워커가 처리하는 작업 큐. Spring은 작업을 넣고 결과를 읽기만 하고, 꺼내기·lease·재시도·완료·실패는 워커가 쓴다.
-- 워커는 FOR UPDATE SKIP LOCKED로 PENDING·RETRY(예약 시각이 지난 것)와 lease가 끝난 RUNNING을 꺼낸다.
-- PDF는 처리 중에만 보관하고 SUCCEEDED·FAILED가 되면 비운다. 공고를 지우면 작업도 함께 지운다.
CREATE TABLE ai_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(50) NOT NULL,
    announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    request_source VARCHAR(20) NOT NULL,
    requested_by VARCHAR(255),
    status VARCHAR(20) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    lease_token UUID,
    lease_until TIMESTAMPTZ,
    file_name VARCHAR(500) NOT NULL,
    pdf_sha256 VARCHAR(64) NOT NULL,
    pdf BYTEA,
    input JSONB,
    result JSONB,
    error_code VARCHAR(50),
    error_message VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    CONSTRAINT ck_ai_jobs_kind CHECK (kind IN ('ANNOUNCEMENT_PDF_EXTRACTION')),
    CONSTRAINT ck_ai_jobs_request_source CHECK (request_source IN ('ADMIN', 'BATCH')),
    CONSTRAINT ck_ai_jobs_status CHECK (status IN ('PENDING', 'RUNNING', 'RETRY', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_ai_jobs_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_ai_jobs_lease CHECK (status <> 'RUNNING' OR (lease_token IS NOT NULL AND lease_until IS NOT NULL)),
    CONSTRAINT ck_ai_jobs_pdf_cleared CHECK (status NOT IN ('SUCCEEDED', 'FAILED') OR pdf IS NULL),
    CONSTRAINT ck_ai_jobs_pdf_pending CHECK (status IN ('SUCCEEDED', 'FAILED') OR pdf IS NOT NULL),
    CONSTRAINT ck_ai_jobs_result CHECK ((status = 'SUCCEEDED') = (result IS NOT NULL)),
    CONSTRAINT ck_ai_jobs_failure CHECK (status <> 'FAILED' OR error_code IS NOT NULL),
    CONSTRAINT ck_ai_jobs_completed CHECK ((status IN ('SUCCEEDED', 'FAILED')) = (completed_at IS NOT NULL))
);

-- 같은 공고에 진행 중인 작업은 하나뿐이다. 재시도를 기다리는 작업도 진행 중으로 보아 유료 호출이 두 번 나가지 않게 한다.
CREATE UNIQUE INDEX ux_ai_jobs_active
    ON ai_jobs (kind, announcement_id) WHERE status IN ('PENDING', 'RUNNING', 'RETRY');

CREATE INDEX idx_ai_jobs_claim
    ON ai_jobs (next_attempt_at, id) WHERE status IN ('PENDING', 'RETRY');

CREATE INDEX idx_ai_jobs_lease
    ON ai_jobs (lease_until, id) WHERE status = 'RUNNING';

CREATE INDEX idx_ai_jobs_latest_succeeded
    ON ai_jobs (kind, announcement_id, completed_at DESC, id DESC) WHERE status = 'SUCCEEDED';

-- 예전 동기 추출 결과를 성공 작업으로 옮긴다. 입력 스냅숏은 없어서 NULL이다.
-- announcement_pdf_extractions는 공유 DB 데이터를 지우지 않는 규칙에 따라 남기고, 애플리케이션은 더 읽지 않는다.
INSERT INTO ai_jobs (kind, announcement_id, request_source, status, attempts, next_attempt_at,
        file_name, pdf_sha256, result, created_at, completed_at)
SELECT 'ANNOUNCEMENT_PDF_EXTRACTION', announcement_id, 'ADMIN', 'SUCCEEDED', 1, created_at,
        file_name, pdf_sha256, result::jsonb, created_at, created_at
FROM announcement_pdf_extractions
ORDER BY id;

-- 워커 역할(toadzip_ai_worker)은 DB 초기화 스크립트와 운영 절차가 만든다. 역할이 있는 DB에서만 권한을 준다.
-- 워커는 작업을 넣거나 지우지 않고, 입력·식별 열은 바꿀 수 없다.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'toadzip_ai_worker') THEN
        GRANT SELECT ON ai_jobs TO toadzip_ai_worker;
        GRANT UPDATE (status, attempts, next_attempt_at, lease_token, lease_until, pdf, result, error_code,
                error_message, started_at, completed_at) ON ai_jobs TO toadzip_ai_worker;
    END IF;
END
$$;
