-- 공고 단지: LH 공고 상세에 나온 단지 하나. 공고를 넘어서는 단지 식별은 연결한 제품 단지 ID뿐이고 이름은 같은 공고 안에서만 키다.
-- 연결 방법: AUTO(주소 규칙 후보 하나), ADMIN(PDF 보정에서 관리자가 정함), MIGRATED(기존 공급행이 가리키던 단지를 옮김).
CREATE TABLE announcement_complexes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    source_complex_name VARCHAR(255) NOT NULL,
    road_address VARCHAR(500),
    total_household_count INTEGER,
    present_in_source BOOLEAN NOT NULL DEFAULT true,
    housing_complex_id BIGINT REFERENCES housing_complexes(id),
    link_method VARCHAR(20),
    linked_by VARCHAR(255),
    linked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_announcement_complexes_name UNIQUE (announcement_id, source_complex_name),
    CONSTRAINT ck_announcement_complexes_link CHECK (
        (housing_complex_id IS NULL AND link_method IS NULL)
        OR (housing_complex_id IS NOT NULL AND link_method IN ('AUTO', 'ADMIN', 'MIGRATED')))
);

CREATE INDEX idx_announcement_complexes_complex ON announcement_complexes (housing_complex_id);

-- LH 공급 한 행이 공급행 하나다. 공고 단지와 LH가 준 대표 전용면적, 매칭 상태를 둔다. 공고 단지를 모르는 행은 비워 둔다.
-- LH 원천으로 만든 공급행은 공급 PNU가 없을 수 있다.
ALTER TABLE supply_rows ADD COLUMN announcement_complex_id BIGINT REFERENCES announcement_complexes(id) ON DELETE SET NULL;
ALTER TABLE supply_rows ADD COLUMN lh_exclusive_area NUMERIC(10, 4);
ALTER TABLE supply_rows ADD COLUMN lh_match_status VARCHAR(30);
ALTER TABLE supply_rows ALTER COLUMN supply_pnu DROP NOT NULL;
ALTER TABLE supply_rows ADD CONSTRAINT ck_supply_rows_lh_match_status
    CHECK (lh_match_status IN ('MATCHED', 'COMPLEX_UNLINKED', 'AREA_UNMATCHED', 'VALUES_MISSING'));
CREATE INDEX idx_supply_rows_announcement_complex ON supply_rows (announcement_complex_id);

-- 공고문 소유 공고가 확정할 때 본 LH 공급 원천 지문과, 그 뒤 원천이 바뀌어 다시 확인해야 하는지.
ALTER TABLE announcements ADD COLUMN lh_supply_fingerprint VARCHAR(64);
ALTER TABLE announcements ADD COLUMN supply_recheck_required BOOLEAN NOT NULL DEFAULT false;
