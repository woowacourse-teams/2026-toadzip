-- LH·SH·GH 공고 정제가 끝내지 못한 원천을 실패 검토 목록에 남긴다. 이전에는 실행 보고서에만 있었다.
CREATE TABLE announcement_refinement_failures (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider varchar(10) NOT NULL,
    source_key varchar(500) NOT NULL,
    source_announcement_identifier varchar(255),
    pan_id varchar(255),
    reason varchar(50) NOT NULL,
    detail varchar(1000) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL,
    last_occurred_at timestamp(6) with time zone NOT NULL,
    occurrence_count integer NOT NULL,
    recurrence_count integer NOT NULL,
    status varchar(20) NOT NULL,
    last_resolved_at timestamp(6) with time zone,
    first_execution_id uuid,
    last_execution_id uuid,
    last_resolved_execution_id uuid,
    last_resolved_by varchar(255),
    CONSTRAINT announcement_refinement_failures_provider_check CHECK (provider IN ('LH', 'SH', 'GH')),
    CONSTRAINT announcement_refinement_failures_reason_check
        CHECK (reason IN ('SOURCE_LOOKUP_FAILED', 'SOURCE_REFINEMENT_FAILED')),
    CONSTRAINT announcement_refinement_failures_status_check CHECK (status IN ('PENDING', 'RESOLVED'))
);

CREATE INDEX idx_announcement_refinement_failures_provider_status
    ON announcement_refinement_failures (provider, status);

CREATE INDEX idx_announcement_refinement_failures_source_reason
    ON announcement_refinement_failures (source_key, reason);
